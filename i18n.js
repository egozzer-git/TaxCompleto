function getLang() { return localStorage.getItem('lang') || 'es'; }
function setLanguage(lang) {
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][k]) el.textContent = translations[lang][k];
  });
  document.querySelectorAll('.lang-current').forEach(el => el.textContent = lang.toUpperCase());
}
document.addEventListener('DOMContentLoaded', () => {
  setLanguage(getLang());
  document.querySelectorAll('.lang-toggle').forEach(btn => {
    btn.addEventListener('click', e => {
      e.preventDefault();
      setLanguage(getLang() === 'es' ? 'en' : 'es');
    });
  });
});